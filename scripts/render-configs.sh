#!/usr/bin/env bash
# Regenerates ALL generated configs from env.sh (single source of truth).
#   usage: scripts/render-configs.sh [all|dns|nginx|firewall]      (default: all)
# DNS     : dns/team-dnsmasq.conf (primary, Mac 1)  dns/team-dnsmasq-backup.conf (backup, Ext A)
# nginx   : nginx/nginx.conf (primary edge, Mac 2)  nginx/nginx-standby.conf (standby edge, Ext E)
# pf      : firewall/backend-A.pf  firewall/backend-B.pf (Ext C)
# Knobs in env.sh: DNS_TTL, APP_RECORD_IP, EXTRA_RECORDS, LB_METHOD, HTTPS_PORT, FIREWALL_EXTRA_ALLOW
# One-off override: APP_RECORD_IP=1.2.3.4 scripts/render-configs.sh dns
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source "$ROOT/env.sh"
WHAT="${1:-all}"
case "$WHAT" in all|dns|nginx|firewall) ;; *) echo "usage: $0 [all|dns|nginx|firewall]"; exit 1 ;; esac

# ---------------------------------------------------------------- DNS
render_dns() {   # $1=outfile $2=role-label $3=listen-ip
  {
    echo "# ${2} - private DNS for ${DOMAIN}"
    echo "# GENERATED by scripts/render-configs.sh from env.sh - edit env.sh, not this file."
    echo "# Listen IP: ${3} | Subnet: ${SUBNET} | Netmask: ${NETMASK} (${NETMASK_HEX})"
    echo "port=53"
    echo "listen-address=127.0.0.1,${3}"
    echo "bind-interfaces"
    echo "# Do not read /etc/resolv.conf or /etc/hosts: only what is written here + explicit upstreams"
    echo "no-resolv"
    echo "no-hosts"
    echo "server=${UPSTREAM_DNS_1}"
    [ -n "${UPSTREAM_DNS_2:-}" ] && echo "server=${UPSTREAM_DNS_2}"
    echo "# Names under ${DOMAIN} are answered ONLY by us (never forwarded to the internet)"
    echo "local=/${DOMAIN}/"
    echo "# TTL (seconds) on our own records = how long clients may cache them (Ext B)"
    echo "local-ttl=${DNS_TTL}"
    echo "# host-record = exact name -> IPv4 (AAAA gets a clean 'no data' answer)"
    echo "# app = the service name (Ext B/E move it); api = control record, always the primary edge"
    echo "host-record=app.${DOMAIN},${APP_RECORD_IP}"
    echo "host-record=api.${DOMAIN},${MAC2_IP}"
    for r in ${EXTRA_RECORDS}; do echo "host-record=${r%%=*}.${DOMAIN},${r#*=}"; done
    echo "# Log every query (live evidence of WHICH server answered WHOM)"
    echo "log-queries"
    echo "log-facility=-"
  } > "$1"
}

# ---------------------------------------------------------------- NGINX
render_nginx() {  # $1=outfile $2=edge-name(primary|standby) $3=host-label $4=ip
  case "$LB_METHOD" in
    least_conn) LB_LINE="least_conn;   # fewest active connections wins" ;;
    ip_hash)    LB_LINE="ip_hash;      # same client IP -> same backend (sticky)" ;;
    *)          LB_LINE="# round-robin (nginx default): A, B, A, B ..." ;;
  esac
  cat > "$1" <<EOF
# Edge (${2}): ${3} ${4} - TLS termination + reverse proxy + load balancer + passive health checks
# GENERATED by scripts/render-configs.sh from env.sh - edit env.sh, not this file.
# Start/stop: scripts/edge-ctl.sh ${2} start|stop|reload
worker_processes 1;
error_log /tmp/nginx-cn-error.log info;
pid       /tmp/nginx-cn.pid;

events { worker_connections 256; }

http {
    default_type application/json;

    # Which backend answered; on failover \$upstream_addr lists EVERY try
    # e.g. upstream=A:3001, B:3002 upstream_status=502, 200
    log_format cn '\$remote_addr:\$remote_port [\$time_local] edge=${2} "\$request" \$status '
                  'upstream=\$upstream_addr upstream_status=\$upstream_status '
                  'X-Backend=\$upstream_http_x_backend rt=\$upstream_response_time';
    access_log /tmp/nginx-cn-access.log cn;

    # ---- UPSTREAM POOL + PASSIVE HEALTH CHECK (Ext D) ----
    # max_fails=1 fail_timeout=10s: one failed attempt marks the server DOWN for 10 s,
    # then nginx tries it again with real traffic -> balancing resumes automatically.
    upstream app_pool {
        ${LB_LINE}
        server ${MAC3_IP}:${BACKEND_A_PORT} max_fails=1 fail_timeout=10s;   # Backend A (Mac 3)
        server ${MAC4_IP}:${BACKEND_B_PORT} max_fails=1 fail_timeout=10s;   # Backend B (Mac 4)
    }

    server {
        listen ${HTTPS_PORT} ssl;
        server_name app.${DOMAIN} api.${DOMAIN};

        # ---- TLS terminates HERE (same cert on primary and standby: it names the domain, not an IP) ----
        ssl_certificate     ${CERT_DIR}/edge.pem;
        ssl_certificate_key ${CERT_DIR}/edge-key.pem;
        ssl_protocols TLSv1.2 TLSv1.3;

        # Which edge answered (Ext E cutover is visible in every response)
        add_header X-Edge ${2} always;

        # The edge's own health, no backend involved (isolates edge vs backend faults)
        location = /edge-health {
            add_header X-Edge ${2} always;
            return 200 '{"edge":"${2}","status":"ok"}\n';
        }

        location / {
            proxy_pass http://app_pool;
            proxy_set_header Host              \$host;
            proxy_set_header X-Real-IP         \$remote_addr;
            proxy_set_header X-Forwarded-For   \$proxy_add_x_forwarded_for;
            proxy_set_header X-Forwarded-Proto https;
            proxy_connect_timeout 1s;           # dead/firewalled backend detected fast
            proxy_read_timeout    5s;
            # retry the SAME request on the other backend -> the client never sees the failure
            proxy_next_upstream error timeout http_502 http_503 http_504;
            proxy_next_upstream_tries 2;
            proxy_next_upstream_timeout 3s;
        }
    }
}
EOF
}

# ---------------------------------------------------------------- FIREWALL (pf)
render_pf() {   # $1=outfile $2=backend-id $3=port
  {
    echo "# Ext C - isolation for Backend ${2} (port ${3}). GENERATED by scripts/render-configs.sh"
    echo "# Loaded into pf anchor com.apple/250.CNIsolation by scripts/firewall.sh (/etc/pf.conf untouched)."
    echo "pass in quick on lo0 all"
    echo "# ONLY the edge (Mac 2) may open TCP connections to the backend port"
    echo "pass in quick proto tcp from ${MAC2_IP} to any port ${3} keep state"
    for ip in ${FIREWALL_EXTRA_ALLOW}; do echo "pass in quick proto tcp from ${ip} to any port ${3} keep state   # extra allow"; done
    echo "# Everyone else: silently dropped (client sees a TIMEOUT, not 'connection refused')"
    echo "block drop in quick proto tcp from any to any port ${3}"
  } > "$1"
}

if [ "$WHAT" = all ] || [ "$WHAT" = dns ]; then
  render_dns "$ROOT/dns/team-dnsmasq.conf"        "Mac 1 PRIMARY DNS (Aryan)" "$MAC1_IP"
  render_dns "$ROOT/dns/team-dnsmasq-backup.conf" "BACKUP DNS ${BACKUP_DNS_LABEL}" "$BACKUP_DNS_IP"
  echo "Rendered DNS  : app.${DOMAIN} -> ${APP_RECORD_IP}, TTL ${DNS_TTL}s ${EXTRA_RECORDS:+(+ $EXTRA_RECORDS)}"
fi
if [ "$WHAT" = all ] || [ "$WHAT" = nginx ]; then
  render_nginx "$ROOT/nginx/nginx.conf"         primary "Mac 2 (Ranajeet)"    "$MAC2_IP"
  render_nginx "$ROOT/nginx/nginx-standby.conf" standby "$STANDBY_EDGE_LABEL" "$STANDBY_EDGE_IP"
  echo "Rendered nginx: port ${HTTPS_PORT}, LB ${LB_METHOD}, upstreams ${MAC3_IP}:${BACKEND_A_PORT} ${MAC4_IP}:${BACKEND_B_PORT}"
fi
if [ "$WHAT" = all ] || [ "$WHAT" = firewall ]; then
  mkdir -p "$ROOT/firewall"
  render_pf "$ROOT/firewall/backend-A.pf" A "$BACKEND_A_PORT"
  render_pf "$ROOT/firewall/backend-B.pf" B "$BACKEND_B_PORT"
  echo "Rendered pf   : only ${MAC2_IP} ${FIREWALL_EXTRA_ALLOW} may reach ${BACKEND_A_PORT}/${BACKEND_B_PORT}"
fi
