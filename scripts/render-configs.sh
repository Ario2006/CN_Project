#!/usr/bin/env bash
# Regenerates ALL generated configs from env.sh (single source of truth).
#   usage: scripts/render-configs.sh [all|dns|nginx|firewall]      (default: all)
# Phase 1 files : dns/team-dnsmasq.conf (Mac 1)   nginx/nginx.conf (Mac 2)
# Phase 2 files : dns/team-dnsmasq-backup.conf (backup DNS, Ext A)
#                 nginx/nginx-standby.conf (standby edge, Ext E)
#                 firewall/backend-A.pf, firewall/backend-B.pf (Ext C)
# Override where app.$DOMAIN points (Ext B/E):  APP_RECORD_IP=1.2.3.4 scripts/render-configs.sh dns
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source "$ROOT/env.sh"
WHAT="${1:-all}"

# ---------------------------------------------------------------- DNS
render_dns() {   # $1=outfile $2=role-label $3=listen-ip
  cat > "$1" <<EOF
# ${2} - private DNS for ${DOMAIN}
# GENERATED by scripts/render-configs.sh from env.sh - edit env.sh, not this file.
# Listen IP: ${3} | Subnet: ${SUBNET} | Netmask: ${NETMASK} (${NETMASK_HEX})
port=53
listen-address=127.0.0.1,${3}
bind-interfaces
# Do not read /etc/resolv.conf or /etc/hosts: only what is written here + explicit upstreams
no-resolv
no-hosts
server=${UPSTREAM_DNS_1}
EOF
  [ -n "${UPSTREAM_DNS_2:-}" ] && echo "server=${UPSTREAM_DNS_2}" >> "$1"
  cat >> "$1" <<EOF
# Names under ${DOMAIN} are answered ONLY by us (never forwarded to the internet)
local=/${DOMAIN}/
# TTL (seconds) put on our own records -> how long clients may cache them (Ext B)
local-ttl=${DNS_TTL}
# app = the service name clients use (Ext B/E move it); api = control record, stays on Mac 2
# host-record (not address=): exact name, AAAA gets a clean NOERROR/no-data instead of NXDOMAIN
host-record=app.${DOMAIN},${APP_RECORD_IP}
host-record=api.${DOMAIN},${MAC2_IP}
# Log every query to the terminal / log file (live evidence of WHICH server answered)
log-queries
log-facility=-
EOF
}

# ---------------------------------------------------------------- NGINX
render_nginx() {  # $1=outfile $2=edge-name(primary|standby) $3=host-label $4=ip
  cat > "$1" <<EOF
# Edge (${2}): ${3} ${4} - TLS termination + reverse proxy + round-robin LB + passive health checks
# GENERATED by scripts/render-configs.sh from env.sh - edit env.sh, not this file.
# Start/stop with scripts/edge-ctl.sh (needs sudo for port ${HTTPS_PORT}).
worker_processes 1;
error_log /tmp/nginx-cn-error.log info;
pid       /tmp/nginx-cn.pid;

events { worker_connections 256; }

http {
    default_type application/json;

    # Which backend answered each request; on failover \$upstream_addr lists EVERY try
    # e.g. upstream=10.7.x.x:3001, 10.7.y.y:3002 upstream_status=502, 200
    log_format cn '\$remote_addr:\$remote_port [\$time_local] edge=${2} "\$request" \$status '
                  'upstream=\$upstream_addr upstream_status=\$upstream_status '
                  'X-Backend=\$upstream_http_x_backend rt=\$upstream_response_time';
    access_log /tmp/nginx-cn-access.log cn;

    # ---- UPSTREAM POOL (round-robin) + PASSIVE HEALTH CHECK (Ext D) ----
    # max_fails=1 fail_timeout=10s: one failed attempt marks the server DOWN for 10 s;
    # after 10 s nginx sends it one trial request again -> traffic resumes automatically.
    # (Active health checks = nginx Plus only; open-source nginx detects failure from real traffic.)
    upstream app_pool {
        server ${MAC3_IP}:${BACKEND_A_PORT} max_fails=1 fail_timeout=10s;   # Backend A (Mac 3)
        server ${MAC4_IP}:${BACKEND_B_PORT} max_fails=1 fail_timeout=10s;   # Backend B (Mac 4)
    }

    server {
        listen ${HTTPS_PORT} ssl;
        server_name app.${DOMAIN} api.${DOMAIN};

        # ---- TLS terminates HERE (same leaf cert on primary and standby edge) ----
        ssl_certificate     ${CERT_DIR}/edge.pem;
        ssl_certificate_key ${CERT_DIR}/edge-key.pem;
        ssl_protocols TLSv1.2 TLSv1.3;

        # Edge identity: lets the client SEE which edge answered (Ext E DNS cutover)
        add_header X-Edge ${2} always;

        # Edge's own liveness endpoint (no backend involved) - useful for layer isolation
        location = /edge-health {
            add_header X-Edge ${2} always;
            return 200 '{"edge":"${2}","status":"ok"}\n';
        }

        location / {
            proxy_pass http://app_pool;
            proxy_set_header Host              \$host;
            proxy_set_header X-Real-IP         \$remote_addr;
            proxy_set_header X-Forwarded-For   \$proxy_add_x_forwarded_for;
            proxy_set_header X-Forwarded-Proto https;
            proxy_connect_timeout 1s;           # dead/firewalled backend detected fast
            proxy_read_timeout    5s;
            # retry the SAME request on the other backend if this one fails -> client never sees it
            proxy_next_upstream error timeout http_502 http_503 http_504;
            proxy_next_upstream_tries 2;
            proxy_next_upstream_timeout 3s;
        }
    }
}
EOF
}

# ---------------------------------------------------------------- FIREWALL (pf)
render_pf() {   # $1=outfile $2=backend-id $3=port
  {
    echo "# Ext C - service isolation for Backend ${2} (port ${3}). GENERATED by scripts/render-configs.sh"
    echo "# Loaded into the pf anchor com.apple/250.CNIsolation by scripts/firewall.sh (never edits /etc/pf.conf)."
    echo "# Same-host traffic (loopback) is always allowed."
    echo "pass in quick on lo0 all"
    echo "# ONLY the edge (Mac 2) may open TCP connections to the backend port"
    echo "pass in quick proto tcp from ${MAC2_IP} to any port ${3} keep state"
    for ip in ${FIREWALL_EXTRA_ALLOW}; do
      echo "pass in quick proto tcp from ${ip} to any port ${3} keep state   # extra allow"
    done
    echo "# Everyone else: silently dropped (client sees a TIMEOUT, not 'connection refused')"
    echo "block drop in quick proto tcp from any to any port ${3}"
  } > "$1"
}

case "$WHAT" in all|dns|nginx|firewall) ;; *) echo "usage: $0 [all|dns|nginx|firewall]"; exit 1 ;; esac

if [ "$WHAT" = all ] || [ "$WHAT" = dns ]; then
  render_dns "$ROOT/dns/team-dnsmasq.conf"        "Mac 1 PRIMARY DNS (Aryan)" "$MAC1_IP"
  render_dns "$ROOT/dns/team-dnsmasq-backup.conf" "BACKUP DNS ${BACKUP_DNS_LABEL}" "$BACKUP_DNS_IP"
  echo "Rendered DNS  (app.${DOMAIN} -> ${APP_RECORD_IP}, TTL ${DNS_TTL}s): dns/team-dnsmasq.conf dns/team-dnsmasq-backup.conf"
fi
if [ "$WHAT" = all ] || [ "$WHAT" = nginx ]; then
  render_nginx "$ROOT/nginx/nginx.conf"         primary "Mac 2 (Ranajeet)"    "$MAC2_IP"
  render_nginx "$ROOT/nginx/nginx-standby.conf" standby "$STANDBY_EDGE_LABEL" "$STANDBY_EDGE_IP"
  echo "Rendered nginx: nginx/nginx.conf nginx/nginx-standby.conf"
fi
if [ "$WHAT" = all ] || [ "$WHAT" = firewall ]; then
  mkdir -p "$ROOT/firewall"
  render_pf "$ROOT/firewall/backend-A.pf" A "$BACKEND_A_PORT"
  render_pf "$ROOT/firewall/backend-B.pf" B "$BACKEND_B_PORT"
  echo "Rendered pf   : firewall/backend-A.pf firewall/backend-B.pf (allow only ${MAC2_IP} ${FIREWALL_EXTRA_ALLOW})"
fi
