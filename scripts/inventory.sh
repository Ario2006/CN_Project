#!/usr/bin/env bash
# Generates docs/ip-service-inventory.md from env.sh (run by sync.sh, so it always matches today's IPs).
#   scripts/inventory.sh            -> writes the file      scripts/inventory.sh -    -> prints to stdout
source "$(dirname "$0")/lib.sh"
OUT="$ROOT/docs/ip-service-inventory.md"; [ "${1:-}" = - ] && OUT=/dev/stdout
cat > "$OUT" <<MD
# IP / Service Inventory

> GENERATED by \`scripts/inventory.sh\` from \`env.sh\` on $(date '+%F %T'). IPs come from DHCP and change day to day; re-run \`scripts/sync.sh\` after \`scripts/set-ip.sh\`.

Network: one private Wi-Fi subnet **${SUBNET}** (netmask **${NETMASK}**, hex **${NETMASK_HEX}**), broadcast **${BROADCAST}**, gateway **${GATEWAY}**, interface **${IFACE}** on every Mac. Domain **${DOMAIN}** (RFC 6761 \`.test\`).

## Hosts

| Mac | Person | Hostname | Phase 1 role | Phase 2 additions | IPv4 | MAC on the air | MAC hardware | Cloud analogue |
|---|---|---|---|---|---|---|---|---|
| 1 | Aryan | \`MacBook-Pro-88\` | primary DNS (dnsmasq) + client | observer client (Ext B/E) | ${MAC1_IP} | \`${MAC1_AIR_MAC}\` | \`${MAC1_HW_MAC}\` | Route 53 private hosted zone |
| 2 | Ranajeet | \`Ranajeets-MacBook-Pro\` | edge: nginx TLS + LB | passive health checks, X-Edge | ${MAC2_IP} | \`${MAC2_AIR_MAC}\` | \`${MAC2_HW_MAC}\` | AWS ALB / CloudFront |
| 3 | Abhijeet | \`Abhijeets-MacBook-Pro-3\` | Backend A | backup DNS, standby edge, pf | ${MAC3_IP} | \`${MAC3_AIR_MAC}\` | \`${MAC3_HW_MAC}\` | EC2 A + 2nd resolver + standby LB |
| 4 | Ankita | \`Ankitas-MacBook-Pro\` | Backend B + client | pf | ${MAC4_IP} | \`${MAC4_AIR_MAC}\` | \`${MAC4_HW_MAC}\` | EC2 B |

## Services

| Service | Host | Socket | Who may connect | Config |
|---|---|---|---|---|
| dnsmasq primary | Mac 1 | ${MAC1_IP}:53/udp | all clients | \`dns/team-dnsmasq.conf\` |
| dnsmasq backup (Ext A) | Mac 3 | ${BACKUP_DNS_IP}:53/udp | all clients | \`dns/team-dnsmasq-backup.conf\` |
| nginx primary edge | Mac 2 | ${MAC2_IP}:${HTTPS_PORT}/tcp | all clients, by name | \`nginx/nginx.conf\` |
| nginx standby edge (Ext E) | Mac 3 | ${STANDBY_EDGE_IP}:${HTTPS_PORT}/tcp | clients after DNS cutover | \`nginx/nginx-standby.conf\` |
| Backend A (REST) | Mac 3 | ${MAC3_IP}:${BACKEND_A_PORT}/tcp | **only Mac 2** with Ext C pf on | \`backend/server.py\`, \`firewall/backend-A.pf\` |
| Backend B (REST) | Mac 4 | ${MAC4_IP}:${BACKEND_B_PORT}/tcp | **only Mac 2** with Ext C pf on | \`backend/server.py\`, \`firewall/backend-B.pf\` |

## DNS records (zone \`${DOMAIN}\`, served identically by both resolvers)

| Name | Type | Answer | TTL | Note |
|---|---|---|---|---|
| app.${DOMAIN} | A | ${APP_RECORD_IP} | ${DNS_TTL} s | the service name; moved during Ext B/E |
| api.${DOMAIN} | A | ${MAC2_IP} | ${DNS_TTL} s | control record, always the primary edge |
MD
for r in ${EXTRA_RECORDS}; do echo "| ${r%%=*}.${DOMAIN} | A | ${r#*=} | ${DNS_TTL} s | extra |" >> "$OUT"; done
[ "$OUT" != /dev/stdout ] && echo "wrote ${OUT#$ROOT/}"
